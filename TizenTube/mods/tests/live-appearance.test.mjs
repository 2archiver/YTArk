import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createLiveAppearance } from '../ui/liveAppearance.js';
import { createDocument, FakeElement, FakeMutationObserver } from './helpers/fake-dom.mjs';

test('semantic TV components are themed without knowing any obfuscated classes and restore on opt-out', () => {
  const d=createDocument();d.body.className='WEB_PAGE_TYPE_BROWSE';
  const guide=new FakeElement('ytlr-guide-response',d);guide.setAttribute('class','obfuscated-a');d.body.appendChild(guide);
  const browse=new FakeElement('ytlr-tv-browse-renderer',d);browse.setAttribute('class','obfuscated-b');d.body.appendChild(browse);
  const video=new FakeElement('video',d);video.style.setProperty('background-color','rgb(17, 34, 51)');d.body.appendChild(video);
  const image=new FakeElement('img',d);d.body.appendChild(image);
  const stage=new FakeElement('yt-unified-overlay-stage',d);d.body.appendChild(stage);
  const boundedPanel=new FakeElement('div',d);boundedPanel.setAttribute('class','ytLrOverlayPanelRendererContent');boundedPanel.__rectWidth=700;boundedPanel.__rectHeight=800;d.body.appendChild(boundedPanel);
  const fullscreenPanel=new FakeElement('div',d);fullscreenPanel.setAttribute('class','ytLrOverlayPanelRendererContent');fullscreenPanel.__rectWidth=1920;fullscreenPanel.__rectHeight=1080;d.body.appendChild(fullscreenPanel);
  const tabList=new FakeElement('div',d);tabList.setAttribute('role','tablist');d.body.appendChild(tabList);
  const tab=new FakeElement('button',d);tab.setAttribute('role','tab');tab.setAttribute('aria-selected','true');tabList.appendChild(tab);
  guide.style.setProperty('background-color','rgb(15, 15, 15)');
  guide.style.setProperty('background-image','linear-gradient(to right, #333, transparent)');
  const settings={oledBlack:true,liquidGlass:false};
  const tasks=[];const w={MutationObserver:FakeMutationObserver,requestAnimationFrame:fn=>{tasks.push(fn);return tasks.length;},cancelAnimationFrame:()=>{},innerWidth:1920,innerHeight:1080,CSS:{supports:()=>true}};
  const theme=createLiveAppearance({documentObject:d,windowObject:w,read:key=>settings[key]});
  theme.start();theme.apply();
  assert.equal(guide.style.getPropertyValue('background-color'),'rgb(0, 0, 0)');
  assert.equal(browse.style.getPropertyValue('background-color'),'rgb(0, 0, 0)');
  assert.equal(guide.style.getPropertyValue('background-image'),'none');
  assert.equal(video.style.getPropertyValue('background-color'),'rgb(17, 34, 51)');
  assert.equal(stage.style.getPropertyValue('background-color'),'');
  assert.equal(boundedPanel.style.getPropertyValue('background-color'),'rgb(0, 0, 0)');
  assert.equal(fullscreenPanel.style.getPropertyValue('background-color'),'');
  settings.liquidGlass=true;theme.apply();
  assert.equal(guide.style.getPropertyValue('background-color'),'rgba(18, 22, 30, 0.92)');
  assert.equal(guide.style.getPropertyValue('backdrop-filter'),'none');
  assert.match(guide.style.getPropertyValue('box-shadow'),/inset 0 0 0 1px/);
  assert.equal(guide.style.getPropertyValue('box-sizing'),'');
  assert.equal(guide.style.getPropertyValue('border-top-width'),'');
  assert.equal(tabList.style.getPropertyValue('background-color'),'rgba(18, 22, 30, 0.92)');
  assert.equal(tab.style.getPropertyValue('background-color'),'rgba(255, 255, 255, 0.16)');
  assert.equal(tab.style.getPropertyValue('box-sizing'),'');
  assert.equal(boundedPanel.style.getPropertyValue('background-color'),'rgba(0, 0, 0, 0.94)');
  assert.equal(boundedPanel.style.getPropertyValue('border-top-width'),'');
  assert.equal(boundedPanel.style.getPropertyValue('box-sizing'),'');
  assert.equal(boundedPanel.style.getPropertyValue('padding'),'');
  assert.equal(fullscreenPanel.style.getPropertyValue('background-color'),'');
  const previous=theme.status().managedNodes;
  for(let i=0;i<25;i++)theme.apply();
  assert.equal(theme.status().managedNodes,previous);
  settings.oledBlack=false;settings.liquidGlass=false;theme.apply();
  assert.equal(guide.style.getPropertyValue('background-color'),'rgb(15, 15, 15)');
  assert.equal(boundedPanel.style.getPropertyValue('background-color'),'');
  assert.equal(tabList.style.getPropertyValue('background-color'),'');
  assert.equal(guide.style.getPropertyValue('border-top-color'),'');
  assert.equal(guide.style.getPropertyValue('background-image'),'linear-gradient(to right, #333, transparent)');
  assert.equal(theme.status().managedNodes,0);
  theme.destroy();
});
