#!/usr/bin/env python3
"""Generate the bundled build-metadata module the app reads its own version from.

Input : release/version.properties (validated by tools/validate_release.py)
Output: TizenTube/mods/assets/buildInfo.generated.js

Why this exists
---------------
About YTArk used to show "Version unknown" because the only version source was
``window.h5vcc.tizentube.GetVersion()``, which the pinned Cobalt base declares
as an *asynchronous* mojo method (``GetVersion() => (string version)`` in
``cobalt/browser/h5vcc_tizentube/public/mojom/h5vcc_tizentube.mojom``). A
synchronous ``String(GetVersion())`` therefore never sees the installed
package's ``versionName``.

The runtime resolver (``TizenTube/mods/features/appVersion.js``) keeps the
installed package metadata as the authority and reads it asynchronously. This
module is the *packaging* half of the fix: it embeds the release's own
metadata in the bundle, so

* a release build can always state which YTArk build it is without any network
  access (no GitHub release lookup, no hardcoded label in the UI code), and
* packaging fails here — instead of shipping "Version Unknown" — when the
  required metadata is missing, malformed or out of sync with
  ``release/version.properties``.

The values are never typed by hand: they are derived from the same
``release/version.properties`` that names the APK, the tag and the versionCode.

Usage::

    python3 tools/build_buildinfo.py --write    # regenerate the module
    python3 tools/build_buildinfo.py --check    # fail if it is stale/missing
    python3 tools/build_buildinfo.py json       # print the metadata
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "TizenTube" / "mods" / "assets" / "buildInfo.generated.js"

sys.path.insert(0, str(ROOT / "tools"))

from validate_release import load_config  # noqa: E402  (shared release contract)

SCHEMA = 1
HEADER = (
    "// Generated by tools/build_buildinfo.py from release/version.properties.\n"
    "// Do not edit by hand: change release/version.properties, then run\n"
    "// `python3 tools/build_buildinfo.py --write`.\n"
    "//\n"
    "// This is packaging metadata for the bundle that is being built. At runtime\n"
    "// the installed package's own versionName (read asynchronously through the\n"
    "// Cobalt bridge) stays the authority for \"YTArk version\"; these values are\n"
    "// the offline fallback and the build details.\n"
)


def build_info() -> dict:
    """Release metadata for this build, validated by the release contract."""
    config = load_config()
    info = {
        "schema": SCHEMA,
        "versionName": config["VERSION_NAME"],
        "displayVersion": config["DISPLAY_VERSION"],
        "versionCode": int(config["VERSION_CODE"]),
        "versionTag": config["VERSION_TAG"],
        "scriptTag": config["SCRIPT_TAG"],
        "baseTag": config["BASE_TAG"],
        "appId": config["APP_ID"],
        "appName": config["APP_NAME"],
        "apkAsset": config["APK_ARMV7"],
    }
    for key, value in info.items():
        if value in ("", None):
            raise ValueError(f"release/version.properties produced an empty {key}")
    return info


def render(info: dict) -> str:
    body = json.dumps(info, indent=2, sort_keys=False)
    return (
        f"{HEADER}"
        f"export const YTARK_BUILD_INFO = {body};\n"
        "export default YTARK_BUILD_INFO;\n"
    )


def display_path(path: Path) -> str:
    """Repository-relative when possible, so a redirected output stays readable."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the module")
    group.add_argument("--check", action="store_true", help="fail when the module is stale or missing")
    group.add_argument("command", nargs="?", choices=("json",), help="print the metadata as JSON")
    args = parser.parse_args()
    if not (args.write or args.check or args.command):
        parser.error("one of --write, --check or `json` is required")

    try:
        info = build_info()
    except (OSError, ValueError) as error:
        print(f"Build metadata is unusable: {error}", file=sys.stderr)
        sys.exit(1)

    if args.command == "json":
        print(json.dumps(info, indent=2))
        return

    expected = render(info)
    if args.check:
        if not OUTPUT.is_file():
            print(
                f"Missing {display_path(OUTPUT)}: the bundle would ship without build "
                "metadata and About YTArk could not state its own version offline.\n"
                "Run `python3 tools/build_buildinfo.py --write`.",
                file=sys.stderr,
            )
            sys.exit(1)
        actual = OUTPUT.read_text(encoding="utf-8")
        if actual != expected:
            print(
                f"{display_path(OUTPUT)} does not match release/version.properties "
                f"({info['versionName']} / {info['versionCode']} / {info['scriptTag']}).\n"
                "Run `python3 tools/build_buildinfo.py --write`.",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"Build metadata module is current: {info['versionName']} ({info['versionCode']}).")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Wrote {display_path(OUTPUT)} for {info['versionName']} ({info['versionCode']}).")


if __name__ == "__main__":
    main()
